"""Write docs/results.md from docs/metrics.json, and verify it is current.

With --check it compares rather than writes, which is what CI runs. A hand
written results table is correct on the day it is written and silently wrong
after the next benchmark run.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
METRICS = ROOT / "docs" / "metrics.json"
TARGET = ROOT / "docs" / "results.md"

NEVER = "never"


def jkey(jitter: float) -> str:
    """Jitter keys in the metrics file are integer percentages, not "0.4"."""
    return str(int(round(jitter * 100)))


def plural(word: str, count: int) -> str:
    return word if count == 1 else word + "s"


def cell(value) -> str:
    return NEVER if value is None else f"{value}"


def render(data: dict) -> str:
    lines: list[str] = []
    add = lines.append
    conditions = data["conditions"]
    guidance = data["guidance"]
    headline = data["headline"]
    jitters = conditions["jitter_grid"]

    add("# Results")
    add("")
    add("Generated by `tools/generate_results_doc.py` from `docs/metrics.json`.")
    add("Reproduce with `make bench`.")
    add("")
    add("## Every figure here is a simulation")
    add("")
    add(data["note"])
    add("")

    add("## The floor, in intervals observed")
    add("")
    add(
        f"The fewest observed intervals at which a detector finds "
        f"{conditions['target_detection_rate']:.0%} of beacons, at a "
        f"{conditions['false_positive_rate']:.0%} false positive rate against non periodic traffic. "
        f"Averaged over {conditions['seeds']} {plural('seed', conditions['seeds'])} of "
        f"{conditions['samples_per_class']} samples per class, "
        f"under the {conditions['jitter_model']} jitter model."
    )
    add("")
    add(
        f"`{NEVER}` means the target was not reached at any point in the grid, which tops out at "
        f"{max(conditions['interval_grid'])} intervals."
    )
    add("")
    add("| detector | " + " | ".join(f"jitter {j:.1f}" for j in jitters) + " |")
    add("| --- | " + " | ".join("---" for _ in jitters) + " |")
    for name, entry in headline.items():
        needed = entry["intervals_needed_by_jitter"]
        add(f"| `{name}` | " + " | ".join(cell(needed[jkey(j)]) for j in jitters) + " |")
    add("")

    reached_everywhere = [
        name
        for name, entry in headline.items()
        if all(v is not None for v in entry["intervals_needed_by_jitter"].values())
    ]
    never_anywhere = [
        name for name, entry in headline.items() if all(v is None for v in entry["intervals_needed_by_jitter"].values())
    ]
    if reached_everywhere:
        add(
            "Reaching the target at every jitter in the grid: "
            + ", ".join(f"`{n}`" for n in reached_everywhere)
            + ". The dispersion statistics hold up better than the spectral ones, which is the "
            "opposite of what the extra machinery in a spectral method suggests."
        )
        add("")
    if never_anywhere:
        add(
            "Never reaching the target anywhere: "
            + ", ".join(f"`{n}`" for n in never_anywhere)
            + ". That is a measured negative result and it is kept rather than deleted. See "
            "[ADR 003](adr/adr-003-keep-the-detector-that-fails.md)."
        )
        add("")

    add("## What each detector cannot see")
    add("")
    add("| detector | needs at least | blind to |")
    add("| --- | --- | --- |")
    for name, entry in headline.items():
        blind = entry["blind_to"].replace("|", "\\|")
        add(f"| `{name}` | {entry['min_intervals']} intervals | {blind} |")
    add("")
    add(
        "Each of these was written before the sweep ran. `bowley-skew` declared that symmetric "
        "jitter is skew free and therefore indistinguishable from no jitter, and the measurement "
        "then found it detecting almost nothing."
    )
    add("")

    add("## The same floor, in hours of capture")
    add("")
    add(
        f"Guidance for beacon hunting recommends capturing at least {guidance['minimum_hours']:.0f} hours, "
        f"with {guidance['ideal_hours']:.0f} being more ideal. A detector does not see a clock, so the "
        "same floor converts into very different capture windows depending on the beacon's period."
    )
    add("")
    hours = data["hours_of_capture"]["interval-cv"]
    periods = ["60", "300", "3600", "86400"]
    labels = {"60": "1 minute", "300": "5 minutes", "3600": "1 hour", "86400": "1 day"}
    add("Hours of capture needed by `interval-cv`, the strongest detector here:")
    add("")
    add("| beacon period | " + " | ".join(f"jitter {j:.1f}" for j in jitters) + " |")
    add("| --- | " + " | ".join("---" for _ in jitters) + " |")
    for period in periods:
        cells = []
        for jitter in jitters:
            row = hours[jkey(jitter)]
            cells.append(NEVER if row is None else f"{row[period]:,.1f}")
        add(f"| {labels[period]} | " + " | ".join(cells) + " |")
    add("")

    worst = hours[jkey(jitters[-1])]
    clean = hours[jkey(jitters[0])]
    if worst and clean:
        add(
            f"A one minute beacon is found inside {worst['60']:.1f} hours even at the worst jitter in the "
            f"grid, so the {guidance['minimum_hours']:.0f} hour advice is generous for it. A daily beacon "
            f"needs {worst['86400']:,.0f} hours at that jitter and {clean['86400']:,.0f} hours with no "
            "jitter at all, which is weeks rather than a day. The guidance is not wrong; the unit hides "
            "a dependency on the thing the hunter does not know."
        )
        add("")

    add("## The jitter model is not a detail")
    add("")
    add(
        "Cobalt Strike's jitter only shortens the sleep: `sleep 300 20` produces 240 to 300 seconds. "
        "The symmetric model most tooling assumes varies the interval both ways, spreading it over "
        "twice the range at the same stated percentage. These are different experiments."
    )
    add("")
    add("| detector | jitter | cobalt-strike | symmetric |")
    add("| --- | --- | --- | --- |")
    for name, entry in data["jitter_models"].items():
        for jitter in jitters:
            key = jkey(jitter)
            left, right = entry["cobalt-strike"][key], entry["symmetric"][key]
            if left is None and right is None:
                continue
            add(f"| `{name}` | {jitter:.1f} | {cell(left)} | {cell(right)} |")
    add("")
    add(
        "A floor quoted at a jitter percentage means two different things depending on which model "
        "was meant, which is worth knowing before comparing any two beacon detection results."
    )
    add("")

    add("## Missed check ins")
    add("")
    misses = data["missed_check_ins"]
    add(
        f"A real beacon misses: a laptop closes, a link drops. With {misses['miss_rate']:.0%} of check ins "
        "removed, the intervals a detector sees include gaps of two and three periods."
    )
    add("")
    add("| detector | jitter 0.4, no misses | jitter 0.4, with misses |")
    add("| --- | --- | --- |")
    for name, entry in misses["detectors"].items():
        add(f"| `{name}` | {cell(entry['no_misses']['40'])} | {cell(entry['with_misses']['40'])} |")
    add("")

    add("## Runtime")
    add("")
    add("| pairs | connections | all five detectors |")
    add("| --- | --- | --- |")
    for row in data["runtime"]:
        add(f"| {row['pairs']:,} | {row['connections']:,} | {row['seconds']:.2f}s |")
    add("")
    biggest = data["runtime"][-1]
    add(
        f"{biggest['connections']:,} connections scored by every detector in {biggest['seconds']:.1f} "
        "seconds, which is a conn.log sized problem on a laptop."
    )
    add("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the file on disk differs")
    args = parser.parse_args(argv)

    if not METRICS.is_file():
        print(f"{METRICS} is absent. Run: make bench", file=sys.stderr)
        return 1

    rendered = render(json.loads(METRICS.read_text(encoding="utf-8")))
    if args.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.is_file() else ""
        if current != rendered:
            print(f"{TARGET} is out of date. Run: python tools/generate_results_doc.py", file=sys.stderr)
            return 1
        print(f"{TARGET.name} matches the metrics")
        return 0

    TARGET.write_text(rendered, encoding="utf-8")
    print(f"wrote {TARGET}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
